#!/usr/bin/env python3
"""
Build data/locked_items.lua from wago.tools DB2 tables.

Items that are locked (lockboxes, junkboxes, locked chests): ItemSparse gives
them a LockID. Only a rogue's Pick Lock (or a key) opens them, so Bagwise does
not tell anyone else to "open" one.

Usage:
    python3 tools/build_locked_items.py
    python3 tools/build_locked_items.py --cache-dir tools/source
    python3 tools/build_locked_items.py --selftest
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_reagent_professions import fetch_csv_table, resolve_build  # noqa: E402

DEFAULT_OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                              "data", "locked_items.lua")
UNUSED_MARKERS = ("Deprecated", "[DNT]", "DNT]", "Test ")


def locked_item_ids(item_sparse_rows):
    """Sorted ids of the items with a lock, leaving out test and deprecated items."""
    ids = set()
    for row in item_sparse_rows:
        try:
            item_id, lock_id = int(row["ID"]), int(row.get("LockID") or 0)
        except (KeyError, ValueError):
            continue
        name = row.get("Display_lang") or ""
        if lock_id and not any(marker in name for marker in UNUSED_MARKERS):
            ids.add(item_id)
    return sorted(ids)


def generate_lua(ids, build):
    lines = ["-- Generated by tools/build_locked_items.py from wago.tools build %s." % build,
             "-- Items with a lock: only a rogue's Pick Lock (or a key) opens them.",
             "Bagwise = Bagwise or {}", "Bagwise.Data = Bagwise.Data or {}",
             "Bagwise.Data.LockedItems = {"]
    lines += ["  [%d] = true," % item_id for item_id in ids]
    lines.append("}")
    return "\n".join(lines) + "\n"


def selftest():
    rows = [{"ID": "4632", "LockID": "5", "Display_lang": "Ornate Bronze Lockbox"},
            {"ID": "3746", "LockID": "2", "Display_lang": "Deprecated Test Strongbox"},
            {"ID": "241233", "LockID": "4050", "Display_lang": "[DNT] Super Strong Lockbox"},
            {"ID": "25", "LockID": "0", "Display_lang": "Worn Shortsword"},
            {"ID": "bad", "LockID": "1"}]
    assert locked_item_ids(rows) == [4632]
    assert "[4632] = true," in generate_lua([4632], "1.0")
    print("selftest ok")


def main():
    ap = argparse.ArgumentParser(description="Generate Bagwise locked_items.lua from wago.tools")
    ap.add_argument("--build", help="Exact build, e.g. 1.60.1.70938. Omit to find the latest Forever build.")
    ap.add_argument("--expansion", default="forever")
    ap.add_argument("--output", default=DEFAULT_OUTPUT)
    ap.add_argument("--cache-dir", help="Cache downloaded CSVs here, keyed by build.")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        selftest()
        return
    build = args.build or resolve_build(args.expansion)
    rows = fetch_csv_table("ItemSparse", build, args.cache_dir)
    ids = locked_item_ids(rows)
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(generate_lua(ids, build))
    print("Wrote %s (%d items)" % (os.path.abspath(args.output), len(ids)))


if __name__ == "__main__":
    main()
