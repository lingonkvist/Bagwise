#!/usr/bin/env python3
"""
Build data/quest_availability.lua: when a quest can be taken.

data/quest_items.lua holds each quest's own level, which is not the level you
can take it at. Vibrant Plumes is a level 60 quest that a level 30 character may
accept, and the war effort "The Alliance Needs Copper Bars!" is level 60 with a
required level of 1. A hint that tells you to bank an item "for a level 60
quest" has to go by the required level, or it flags quests you can do today.

Two tables are written, both only for quests listed in data/quest_items.lua:
  QuestRequiredLevels  quest ID -> level needed to accept it, when that is high
                       enough to matter (a quest open from level 10 or below is
                       never "far above" anyone)
  QuestEvents          quest ID -> the event that offers it (Darkmoon Faire and
                       other holidays), from Questie's quest category. Such a
                       quest can only be done while the event runs.
A quest with no entry is unknown, and Bagwise says nothing about it.

Use the same Questie export as build_quest_items.py, so the two files describe
the same quests:
    python3 tools/build_quest_availability.py --source ../QuestieDB/src/corrections/Forever/combined/foreverQuestDB.lua
    python3 tools/build_quest_availability.py --selftest        (no files needed)

Questie data is licensed under GPL-3.0. Requirements: Python 3.8+, stdlib only.
"""

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_quest_items as quest_source  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
QUEST_FILE = ROOT / "data" / "quest_items.lua"
OUT_FILE = ROOT / "data" / "quest_availability.lua"

REQUIRED_LEVEL = 4      # Questie quest field: the level needed to accept it
ZONE_OR_SORT = 17       # Questie quest field: positive = zone, negative = category
MIN_LEVEL_THAT_MATTERS = 11

# Questie quest categories (negative zoneOrSort values) that are an event, with
# the name shown to the player ("Bank it, for a Darkmoon Faire quest").
EVENT_SORTS = {
    -364: "Darkmoon Faire",
    -366: "Lunar Festival",
    -369: "Midsummer Fire Festival",
    -22: "seasonal event",
    -368: "Scourge Invasion",
}


def quest_ids_in(quest_items_text):
    """The quest IDs that QuestInfo describes in data/quest_items.lua."""
    start = quest_items_text.index("Bagwise.Data.QuestInfo")
    end = quest_items_text.index("Bagwise.Data.RepeatableQuests")
    return {int(n) for n in re.findall(r"^    \[(\d+)\] = \{ ", quest_items_text[start:end], re.M)}


def required_levels(quests, wanted):
    """quests: quest id -> list of raw fields. Returns quest id -> required level."""
    found = {}
    for quest_id in wanted:
        fields = quests.get(quest_id)
        if not fields or len(fields) < REQUIRED_LEVEL:
            continue
        level = quest_source.parse_int(fields[REQUIRED_LEVEL - 1])
        if level and level >= MIN_LEVEL_THAT_MATTERS:
            found[quest_id] = level
    return found


def quest_events(quests, wanted):
    """quests: quest id -> list of raw fields. Returns quest id -> event name."""
    found = {}
    for quest_id in wanted:
        fields = quests.get(quest_id)
        if not fields or len(fields) < ZONE_OR_SORT:
            continue
        name = EVENT_SORTS.get(quest_source.parse_int(fields[ZONE_OR_SORT - 1]))
        if name:
            found[quest_id] = name
    return found


def render_lua(levels, events, source_name):
    lines = [
        "-- Generated by tools/build_quest_availability.py from Questie's %s." % source_name,
        "-- Questie data is licensed under GPL-3.0.  See COPYING and source/ATTRIBUTION.md.",
        "--",
        "-- QuestRequiredLevels: quest ID -> the level you must be to accept the quest.",
        "-- Not the quest's own level (QuestInfo): a level 60 quest can be taken at 30.",
        "-- A quest with no entry is unknown or open from a low level, and Bagwise",
        "-- never calls it far above you.",
        "--",
        "-- QuestEvents: quest ID -> the event that offers the quest, which can only be",
        "-- done while that event runs.",
        "",
        "Bagwise = Bagwise or {}",
        "Bagwise.Data = Bagwise.Data or {}",
        "",
        "Bagwise.Data.QuestRequiredLevels = {",
    ]
    lines += ["  [%d] = %d," % (quest_id, levels[quest_id]) for quest_id in sorted(levels)]
    lines += ["}", "", "Bagwise.Data.QuestEvents = {"]
    lines += ['  [%d] = "%s",' % (quest_id, events[quest_id]) for quest_id in sorted(events)]
    lines.append("}")
    return "\n".join(lines) + "\n"


def selftest():
    items_text = (
        "Bagwise.Data.QuestItems = {\n    [1] = { 10 },\n}\n"
        "Bagwise.Data.QuestInfo = {\n"
        '    [10] = { 60, nil, "Vibrant Plumes" },\n'
        '    [11] = { 60, nil, "The Alliance Needs Copper Bars!", "A" },\n'
        '    [12] = { 20, "Duskwood", "Deep Trouble" },\n'
        '    [13] = { 55, "Tanaris", "Unlisted In Source" },\n'
        "}\n"
        "Bagwise.Data.RepeatableQuests = {\n}\n"
    )
    wanted = quest_ids_in(items_text)
    assert wanted == {10, 11, 12, 13}, wanted
    quests = {
        10: ['"Vibrant Plumes"', "{{14829}}", "{{14829}}", "30", "60"],
        11: ['"Copper"', "nil", "nil", "1", "60"],
        12: ['"Deep Trouble"', "nil", "nil", "17", "20"] + ["nil"] * 11 + ["10"],
        99: ['"Not wanted"', "nil", "nil", "40", "45"],
    }
    quests[10] = quests[10] + ["nil"] * 11 + ["-364"]
    found = required_levels(quests, wanted)
    assert found == {10: 30, 12: 17}, found
    events = quest_events(quests, wanted)
    assert events == {10: "Darkmoon Faire"}, events
    out = render_lua(found, events, "test.lua")
    assert "[10] = 30," in out and "[11]" not in out and "[99]" not in out, out
    assert '[10] = "Darkmoon Faire",' in out, out
    print("build_quest_availability selftest ok")


def main(argv):
    parser = argparse.ArgumentParser(description="Generate quest_availability.lua")
    parser.add_argument("--source", help="Questie's foreverQuestDB.lua (the merged export)")
    parser.add_argument("--output", "-o", default=str(OUT_FILE))
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args(argv)
    if args.selftest:
        selftest()
        return 0
    if not args.source:
        parser.error("--source is required")

    quests, _ = quest_source.parse_quests(Path(args.source))
    wanted = quest_ids_in(QUEST_FILE.read_text(encoding="utf-8"))
    levels = required_levels(quests, wanted)
    events = quest_events(quests, wanted)
    missing = [quest_id for quest_id in wanted if quest_id not in quests]
    Path(args.output).write_text(render_lua(levels, events, Path(args.source).name), encoding="utf-8", newline="\n")
    print("%d of %d quests have a required level, %d are event quests (%d are not in this source)"
          % (len(levels), len(wanted), len(events), len(missing)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
