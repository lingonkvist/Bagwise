#!/usr/bin/env python3
"""
Build data/library_books.lua: the item IDs of the WoW Forever library books.

Players loot these books around the world and hand them in one by one to the
librarian in Stormwind or Undercity for rewards. The game will not give a
deleted book back, so Bagwise gives them a yellow hint. The books are items
that start a quest named after the book, so the item IDs come from the quest
data already in data/quest_items.lua (itself built from Questie): find the quest
with each book's name, then every item tied to that quest.

Usage:
    python3 tools/build_library_books.py            (reads and writes data/)
    python3 tools/build_library_books.py --selftest (no files needed)

Add a name to BOOKS when a new book ships. Requirements: Python 3.8+, stdlib only.
"""

import os
import re
import sys

BOOKS = [
    "A Ludite's Guide to Caring for Your Demonic Pet",
    "A Mind of Metal",
    "A Study of the Light",
    "A Web of Lies: Debunking Myths and Legends",
    "Arcanic Systems Manual",
    "Archmage Antonidas: The Unabridged Autobiography",
    "Archmage Theocritus' Research Journal",
    "Ataeric: On Arcane Curiosities",
    "Basilisks: Should Petrification be Feared?",
    "Baxtan: On Destructive Magics",
    "Bewitchments and Glamours",
    "Conjurer's Codex",
    "Crimes Against Anatomy",
    "Defensive Magics 101",
    "Demons and You",
    "Everyday Etiquette",
    "Fury of the Land",
    "Geomancy: The Stone-Cold Truth",
    "Goaz Scrolls",
    "Ka-Boom!",
    "Legends of the Tidesages",
    "Magma or Lava?",
    "Mummies: A Guide to the Unsavory Undead",
    "Necromancy 101",
    "Nar'thalas Almanac",
    "Northern Kalimdor - A Comprehensive Guide",
    "Rumi of Gnomeregan: The Collected Works",
    "Runes of the Sorcerer-Kings",
    "RwlRwlRwlRwl!",
    "Sanguine Sorcery",
    "Secrets of the Dreamers",
    "Scourge: Undead Menace or Misunderstood?",
    "Stonewrought Design",
    "The Apothecary's Metaphysical Primer",
    "The Dalaran Digest",
    "The Knight and the Lady",
    "The Lessons of Ta'zo",
    "The Liminal and the Arcane",
    "Undead Potatoes",
    "Venomous Journeys",
]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QUEST_FILE = os.path.join(ROOT, "data", "quest_items.lua")
OUT_FILE = os.path.join(ROOT, "data", "library_books.lua")


def normal(name):
    """Name without case, spaces or punctuation, so apostrophes cannot matter."""
    return re.sub(r"[^a-z0-9]", "", name.lower())


def section(source, start, end):
    first = source.index(start)
    return source[first:source.index(end, first)] if end else source[first:]


def parse_quest_data(source):
    """Return (items, quests): item id -> [quest ids], quest id -> (name, hasZone)."""
    item_text = section(source, "Bagwise.Data.QuestItems", "Bagwise.Data.QuestInfo")
    items = {}
    for key, body in re.findall(r"\[(\d+)\] = \{([^}]*)\}", item_text):
        items[int(key)] = [int(n) for n in body.split(",") if n.strip()]

    info_text = section(source, "Bagwise.Data.QuestInfo", "Bagwise.Data.RepeatableQuests")
    quests = {}
    for key, body in re.findall(r"\[(\d+)\] = \{ ([^\n]*?) \},?\n", info_text):
        names = re.findall(r'"([^"]*)"', body)
        if not names:
            continue
        has_zone = ", nil," not in body and len(names) > 1
        quests[int(key)] = (names[1] if has_zone else names[0], has_zone)
    return items, quests


def find_books(items, quests):
    """Return (book item ids, names with no quest found)."""
    wanted = {normal(name): name for name in BOOKS}
    book_quests = {}
    for quest_id, (name, has_zone) in quests.items():
        # The book quests have no zone. A zone quest of the same name is a
        # different quest.
        if has_zone:
            continue
        key = normal(name)
        if key in wanted:
            book_quests.setdefault(key, set()).add(quest_id)

    found = set()
    for quest_ids in book_quests.values():
        for item_id, item_quests in items.items():
            if quest_ids.intersection(item_quests):
                found.add(item_id)
    missing = [wanted[key] for key in wanted if key not in book_quests]
    return sorted(found), missing


def render_lua(item_ids):
    lines = [
        "-- Generated by tools/build_library_books.py from data/quest_items.lua.",
        "--",
        "-- LibraryBooks: item ID -> true, for the Forever library books. Players hand",
        "-- them in one by one to the librarian in Stormwind or Undercity, and the game",
        "-- will not give a deleted one back.",
        "",
        "Bagwise = Bagwise or {}",
        "Bagwise.Data = Bagwise.Data or {}",
        "",
        "Bagwise.Data.LibraryBooks = {",
    ]
    lines += ["  [%d] = true," % item_id for item_id in item_ids]
    lines.append("}")
    return "\n".join(lines) + "\n"


def selftest():
    sample = (
        "Bagwise.Data.QuestItems = {\n"
        "    [100] = { 1 },\n"
        "    [101] = { 2, 3 },\n"
        "    [102] = { 4 },\n"
        "}\n"
        "Bagwise.Data.QuestInfo = {\n"
        '    [1] = { 20, nil, "Goaz Scrolls" },\n'
        '    [2] = { 20, nil, "Archmage Theocritus\' Research Journal" },\n'
        '    [3] = { 5, "Elwynn Forest", "Goaz Scrolls" },\n'
        '    [4] = { 5, "Elwynn Forest", "Some Other Quest" },\n'
        "}\n"
        "Bagwise.Data.RepeatableQuests = {\n}\n"
    )
    items, quests = parse_quest_data(sample)
    assert items == {100: [1], 101: [2, 3], 102: [4]}, items
    assert quests[1] == ("Goaz Scrolls", False), quests
    assert quests[3] == ("Goaz Scrolls", True), quests
    found, missing = find_books(items, quests)
    assert found == [100, 101], found
    assert "Goaz Scrolls" not in missing and "Ka-Boom!" in missing, missing
    out = render_lua(found)
    assert "[100] = true," in out and "[102]" not in out, out
    assert normal("Theocritus' Journal") == normal("Theocritus journal")
    print("build_library_books selftest ok")


def main(argv):
    if "--selftest" in argv:
        selftest()
        return 0
    with open(QUEST_FILE, encoding="utf-8") as handle:
        items, quests = parse_quest_data(handle.read())
    found, missing = find_books(items, quests)
    for name in missing:
        print("no quest found for: " + name, file=sys.stderr)
    if not found:
        print("no books found, nothing written", file=sys.stderr)
        return 1
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_lua(found))
    print("wrote %d book items to %s" % (len(found), OUT_FILE))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
